#!/usr/bin/env python3
"""tools/calibrate_from_report.py - Extract optimal Strata serving parameters from benchmark reports.

Parses report.md (or JSON) generated by tools/run_xe2_perf_benchmarks.py or Google Benchmark,
analyzes kernel latencies and bandwidths, and outputs calibrated environment settings
for Intel Arc B580 and Lunar Lake GPUs.

Usage:
    python3 tools/calibrate_from_report.py bench_results/tier3_run/report.md
    python3 tools/calibrate_from_report.py --latest
    python3 tools/calibrate_from_report.py report.md --write-config strata-b580-iq2xs.json
    eval $(python3 tools/calibrate_from_report.py report.md --export)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent


def parse_latency_us(lat_str: str) -> Optional[float]:
    """Parse latency string like '23.1 µs', '1.06 ms', '450.0 ns' into microseconds."""
    lat_str = lat_str.strip().replace(",", "")
    m = re.match(r"^([\d.]+)\s*(ns|µs|us|ms|s)$", lat_str)
    if not m:
        return None
    val, unit = float(m.group(1)), m.group(2)
    if unit == "ns":
        return val / 1000.0
    elif unit in ("µs", "us"):
        return val
    elif unit == "ms":
        return val * 1000.0
    elif unit == "s":
        return val * 1_000_000.0
    return None


def parse_bandwidth_gbps(bw_str: str) -> Optional[float]:
    """Parse bandwidth string like '58.1 GB/s', '101.14 GB/s' into GB/s."""
    bw_str = bw_str.strip().replace(",", "")
    m = re.search(r"([\d.]+)\s*GB/s", bw_str)
    if m:
        return float(m.group(1))
    return None


class ReportCalibrator:
    def __init__(self, content: str):
        self.text = content
        self.lines = content.splitlines()
        self.device_name = "Unknown Intel GPU"
        self.microarch = "Intel Xe2"
        self.compute_units = 0
        self.is_bmg = False

        self._parse_metadata()

    def _parse_metadata(self):
        for line in self.lines[:30]:
            if "Target Hardware" in line:
                m = re.search(r"`([^`]+)`", line) or re.search(r":\s*(.+)", line)
                if m:
                    self.device_name = m.group(1).strip()
            elif "Microarchitecture" in line:
                m = re.search(r":\s*(.+)", line)
                if m:
                    self.microarch = m.group(1).strip()
            elif "Compute Units" in line:
                m = re.search(r"(\d+)\s*(?:multiprocessors|compute units|CUs|cores)", line, re.IGNORECASE)
                if m:
                    self.compute_units = int(m.group(1))

        dev_upper = self.device_name.upper()
        self.is_bmg = (
            "B580" in dev_upper
            or "BMG" in dev_upper
            or "B570" in dev_upper
            or "ARC PRO B" in dev_upper
            or self.compute_units >= 128
        )

    def extract_split_k(self) -> Tuple[int, str]:
        """Determine optimal STRATA_XE2_SPLIT_K from KV decode benchmarks."""
        # Look for BM_Xe2_KV_Decode_INT8_SplitK/<T>/<splits> or FP16_SplitK
        split_bws: Dict[int, List[float]] = {}
        pattern = re.compile(
            r"BM_Xe2_KV_Decode_(?:INT8|FP16)_SplitK/(\d+)/(\d+).*?\|\s*([\d.]+)\s*(?:µs|us|ms).*?\|\s*([\d.]+)\s*GB/s"
        )

        for line in self.lines:
            m = pattern.search(line)
            if m:
                t_ctx = int(m.group(1))
                splits = int(m.group(2))
                bw = float(m.group(4))
                # Focus on long contexts T >= 16384 where Split-K parallelism matters
                if t_ctx >= 16384:
                    split_bws.setdefault(splits, []).append(bw)

        if split_bws:
            best_split = max(split_bws.keys(), key=lambda s: sum(split_bws[s]) / len(split_bws[s]))
            avg_bw = sum(split_bws[best_split]) / len(split_bws[best_split])
            return best_split, f"Measured peak bandwidth {avg_bw:.1f} GB/s at T>=16K with {best_split} splits"

        # Fallback based on architecture
        if self.is_bmg:
            return 32, "Default for Arc B580 (20 Xe-cores, 160 VEs): 32 splits"
        return 1, "Default for Lunar Lake (8 Xe-cores): 1 split"

    def extract_slm_pad(self) -> Tuple[int, str]:
        """Determine optimal STRATA_XE2_SLM_PAD from fused GDN benchmarks."""
        pad_perf: Dict[int, List[float]] = {}
        # Matches: BM_Xe2_GDN_Fused_SLM_Padded<8>/... or counters Pad_Elements=8
        pad_pat = re.compile(r"BM_Xe2_GDN_Fused_SLM_Padded<(\d+)>.*?\|\s*([\d.]+)\s*(ns|µs|us|ms)")
        counter_pat = re.compile(r"Pad_Elements=(\d+)")

        for line in self.lines:
            m = pad_pat.search(line)
            if m:
                pad = int(m.group(1))
                lat = parse_latency_us(f"{m.group(2)} {m.group(3)}")
                if lat:
                    pad_perf.setdefault(pad, []).append(lat)
            elif "BM_Xe2_GDN_Fused_SLM" in line and "Pad_Elements" in line:
                mc = counter_pat.search(line)
                ml = re.search(r"\|\s*([\d.]+)\s*(ns|µs|us|ms)", line)
                if mc and ml:
                    pad = int(mc.group(1))
                    lat = parse_latency_us(f"{ml.group(1)} {ml.group(2)}")
                    if lat:
                        pad_perf.setdefault(pad, []).append(lat)

        if pad_perf:
            best_pad = min(pad_perf.keys(), key=lambda p: sum(pad_perf[p]) / len(pad_perf[p]))
            avg_lat = sum(pad_perf[best_pad]) / len(pad_perf[best_pad])
            return best_pad, f"Lowest latency ({avg_lat:.1f} µs) with {best_pad}-element padding"

        if self.is_bmg:
            return 8, "Default for Arc B580: 8-element padding (prevents 64-byte SLM bank conflicts)"
        return 0, "Default for Lunar Lake: 0-element padding"

    def extract_dual_column(self) -> Tuple[int, str]:
        """Determine optimal STRATA_XE2_DUAL_COLUMN from MoE SwiGLU benchmarks."""
        sep_lat: Optional[float] = None
        dual_lat: Optional[float] = None

        for line in self.lines:
            if "BM_Xe2_MoE_Separate_Gate_Up_SwiGLU/1" in line:
                m = re.search(r"\|\s*([\d.]+)\s*(ns|µs|us|ms)", line)
                if m:
                    sep_lat = parse_latency_us(f"{m.group(1)} {m.group(2)}")
            elif "BM_Xe2_MoE_DualColumn_SwiGLU/1" in line:
                m = re.search(r"\|\s*([\d.]+)\s*(ns|µs|us|ms)", line)
                if m:
                    dual_lat = parse_latency_us(f"{m.group(1)} {m.group(2)}")

        if sep_lat and dual_lat:
            if dual_lat < sep_lat:
                speedup = sep_lat / dual_lat
                return 1, f"Dual-column SwiGLU is {speedup:.2f}x faster ({dual_lat:.1f} µs vs {sep_lat:.1f} µs)"
            else:
                return 0, f"Separate kernels faster or equal ({sep_lat:.1f} µs vs {dual_lat:.1f} µs)"

        return 0, "Opt-in: default 0 (preserves byte-exact parity); enable 1 for fast decode"

    def extract_cache_hint(self) -> Tuple[int, str]:
        """Determine optimal STRATA_XE2_CACHE_HINT from residual pipeline benchmarks."""
        for line in self.lines:
            if "Hyper-Connection Residual Ping-Pong" in line or "perf_residual_pipeline" in line:
                # Check for mention of speedup in executive summary or table
                m = re.search(r"Fused:\s*[\d.]+\s*µs\s*vs\s*Unfused:\s*[\d.]+\s*µs\s*\(([\d.]+)x", line)
                if m:
                    ratio = float(m.group(1))
                    if ratio >= 1.0:
                        return 1, f"Streaming cache hints maintain L2/L3 residency ({ratio:.2f}x speedup)"

        if self.is_bmg:
            return 1, "Default for Arc B580: non-temporal load hints stream weights without evicting KV cache"
        return 0, "Default for Lunar Lake: disabled on unified LPDDR5x"

    def extract_prefill_chunk(self) -> Tuple[int, str]:
        """Determine recommended --prefill chunk size from prefill GEMM / QSA benchmarks."""
        chunk_tflops: Dict[int, float] = {}
        for line in self.lines:
            if "BM_Xe2_Prefill_GEMM" in line:
                m_chunk = re.search(r"Chunk_M=(\d+)", line)
                m_tf = re.search(r"([\d.]+)\s*TFLOPS", line)
                if m_chunk and m_tf:
                    chunk_tflops[int(m_chunk.group(1))] = float(m_tf.group(1))

        if chunk_tflops:
            best_chunk = max(chunk_tflops.keys(), key=lambda c: chunk_tflops[c])
            return best_chunk, f"Peak prefill throughput ({chunk_tflops[best_chunk]:.2f} TFLOPS) at chunk {best_chunk}"

        if self.is_bmg:
            return 2048, "Recommended for Arc B580: 2048 chunk size"
        return 512, "Recommended for Lunar Lake: 512 chunk size"

    def calibrate(self) -> Dict[str, Any]:
        split_k, split_k_reason = self.extract_split_k()
        slm_pad, slm_pad_reason = self.extract_slm_pad()
        dual_col, dual_col_reason = self.extract_dual_column()
        cache_hint, cache_hint_reason = self.extract_cache_hint()
        prefill, prefill_reason = self.extract_prefill_chunk()

        return {
            "device": {
                "name": self.device_name,
                "microarch": self.microarch,
                "compute_units": self.compute_units,
                "is_bmg": self.is_bmg,
            },
            "parameters": {
                "STRATA_XE2_SPLIT_K": split_k,
                "STRATA_XE2_SLM_PAD": slm_pad,
                "STRATA_XE2_DUAL_COLUMN": dual_col,
                "STRATA_XE2_CACHE_HINT": cache_hint,
                "PREFILL_CHUNK": prefill,
            },
            "rationales": {
                "STRATA_XE2_SPLIT_K": split_k_reason,
                "STRATA_XE2_SLM_PAD": slm_pad_reason,
                "STRATA_XE2_DUAL_COLUMN": dual_col_reason,
                "STRATA_XE2_CACHE_HINT": cache_hint_reason,
                "PREFILL_CHUNK": prefill_reason,
            },
        }


def format_report_summary(cal: Dict[str, Any]) -> str:
    dev = cal["device"]
    params = cal["parameters"]
    reasons = cal["rationales"]

    target_type = "Intel Arc B580 Desktop (Discrete Xe2)" if dev["is_bmg"] else "Intel Lunar Lake (Integrated Xe2)"

    lines = [
        "=================================================================",
        " Strata Performance Tuning Calibration Summary",
        f" Target Hardware:  {dev['name']} ({target_type})",
        f" Architecture:     {dev['microarch']} ({dev['compute_units']} CUs)",
        "=================================================================",
        "",
        "| Environment Parameter   | Calibrated Value | Calibration Rationale |",
        "| :---------------------- | :--------------- | :-------------------- |",
        f"| `STRATA_XE2_SPLIT_K`    | `{params['STRATA_XE2_SPLIT_K']}` | {reasons['STRATA_XE2_SPLIT_K']} |",
        f"| `STRATA_XE2_SLM_PAD`    | `{params['STRATA_XE2_SLM_PAD']}` | {reasons['STRATA_XE2_SLM_PAD']} |",
        f"| `STRATA_XE2_DUAL_COLUMN`| `{params['STRATA_XE2_DUAL_COLUMN']}` | {reasons['STRATA_XE2_DUAL_COLUMN']} |",
        f"| `STRATA_XE2_CACHE_HINT` | `{params['STRATA_XE2_CACHE_HINT']}` | {reasons['STRATA_XE2_CACHE_HINT']} |",
        f"| CLI `--prefill`         | `{params['PREFILL_CHUNK']}` | {reasons['PREFILL_CHUNK']} |",
        "",
        "-----------------------------------------------------------------",
        " 1. Shell Export Commands (Copy-Paste into Terminal):",
        "-----------------------------------------------------------------",
        f"export STRATA_XE2_SPLIT_K={params['STRATA_XE2_SPLIT_K']}",
        f"export STRATA_XE2_SLM_PAD={params['STRATA_XE2_SLM_PAD']}",
        f"export STRATA_XE2_DUAL_COLUMN={params['STRATA_XE2_DUAL_COLUMN']}",
        f"export STRATA_XE2_CACHE_HINT={params['STRATA_XE2_CACHE_HINT']}",
        "",
        "-----------------------------------------------------------------",
        " 2. Server Configuration Fragment (for strata-*.json 'env' block):",
        "-----------------------------------------------------------------",
        json.dumps(
            {
                "SYCL_CACHE_PERSISTENT": "0",
                "ONEAPI_DEVICE_SELECTOR": "level_zero:0",
                "ZES_ENABLE_SYSMAN": "1",
                "STRATA_XE2_SPLIT_K": str(params["STRATA_XE2_SPLIT_K"]),
                "STRATA_XE2_SLM_PAD": str(params["STRATA_XE2_SLM_PAD"]),
                "STRATA_XE2_CACHE_HINT": str(params["STRATA_XE2_CACHE_HINT"]),
                "STRATA_XE2_DUAL_COLUMN": str(params["STRATA_XE2_DUAL_COLUMN"]),
            },
            indent=2,
        ),
        "",
    ]
    return "\n".join(lines)


def update_json_config(config_path: Path, cal: Dict[str, Any]):
    """Update or create the 'env' section of a Strata server config JSON file."""
    if not config_path.exists():
        print(f"[ERROR] Target config file does not exist: {config_path}", file=sys.stderr)
        sys.exit(1)

    try:
        data = json.loads(config_path.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[ERROR] Failed to read JSON config {config_path}: {e}", file=sys.stderr)
        sys.exit(1)

    params = cal["parameters"]
    env_block = data.get("env", {})
    env_block["STRATA_XE2_SPLIT_K"] = str(params["STRATA_XE2_SPLIT_K"])
    env_block["STRATA_XE2_SLM_PAD"] = str(params["STRATA_XE2_SLM_PAD"])
    env_block["STRATA_XE2_CACHE_HINT"] = str(params["STRATA_XE2_CACHE_HINT"])
    env_block["STRATA_XE2_DUAL_COLUMN"] = str(params["STRATA_XE2_DUAL_COLUMN"])
    data["env"] = env_block

    config_path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(f"[OK] Successfully updated 'env' calibration settings in: {config_path}")


def find_latest_report() -> Optional[Path]:
    """Find the most recent report.md in bench_results or perf/results."""
    candidates = list(ROOT.glob("bench_results/**/report.md")) + list(ROOT.glob("perf/results/**/report.md"))
    if not candidates:
        return None
    candidates.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    return candidates[0]


def main():
    parser = argparse.ArgumentParser(
        description="Extract optimal Strata serving parameters from benchmark report.md",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "report",
        nargs="?",
        help="Path to report.md, results directory, or JSON file. Omit with --latest to find the newest report.",
    )
    parser.add_argument(
        "--latest",
        action="store_true",
        help="Automatically locate and parse the most recent report.md in bench_results/",
    )
    parser.add_argument(
        "--write-config",
        metavar="CONFIG_JSON",
        help="Directly write calibrated 'env' parameters to a Strata server config file",
    )
    parser.add_argument(
        "--export",
        action="store_true",
        help="Output shell export statements only (for eval $(python3 ... --export))",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Output calibration results as machine-readable JSON",
    )

    args = parser.parse_args()

    report_path: Optional[Path] = None
    if args.report:
        p = Path(args.report)
        if p.is_dir():
            md_cand = p / "report.md"
            if md_cand.exists():
                report_path = md_cand
            else:
                print(f"[ERROR] Directory does not contain report.md: {p}", file=sys.stderr)
                sys.exit(1)
        else:
            report_path = p
    elif args.latest:
        report_path = find_latest_report()
        if not report_path:
            print("[ERROR] No report.md found in bench_results/ or perf/results/", file=sys.stderr)
            sys.exit(1)
    else:
        # Check if stdin has data
        if not sys.stdin.isatty():
            content = sys.stdin.read()
            cal = ReportCalibrator(content).calibrate()
            if args.export:
                p = cal["parameters"]
                print(f"export STRATA_XE2_SPLIT_K={p['STRATA_XE2_SPLIT_K']}")
                print(f"export STRATA_XE2_SLM_PAD={p['STRATA_XE2_SLM_PAD']}")
                print(f"export STRATA_XE2_DUAL_COLUMN={p['STRATA_XE2_DUAL_COLUMN']}")
                print(f"export STRATA_XE2_CACHE_HINT={p['STRATA_XE2_CACHE_HINT']}")
            elif args.json:
                print(json.dumps(cal, indent=2))
            else:
                print(format_report_summary(cal))
            return
        else:
            # Auto-fallback to latest report if available
            report_path = find_latest_report()
            if not report_path:
                parser.print_help()
                sys.exit(1)

    if not report_path.exists():
        print(f"[ERROR] File not found: {report_path}", file=sys.stderr)
        sys.exit(1)

    content = report_path.read_text(encoding="utf-8")
    cal = ReportCalibrator(content).calibrate()

    if args.write_config:
        update_json_config(Path(args.write_config), cal)

    if args.export:
        p = cal["parameters"]
        print(f"export STRATA_XE2_SPLIT_K={p['STRATA_XE2_SPLIT_K']}")
        print(f"export STRATA_XE2_SLM_PAD={p['STRATA_XE2_SLM_PAD']}")
        print(f"export STRATA_XE2_DUAL_COLUMN={p['STRATA_XE2_DUAL_COLUMN']}")
        print(f"export STRATA_XE2_CACHE_HINT={p['STRATA_XE2_CACHE_HINT']}")
    elif args.json:
        print(json.dumps(cal, indent=2))
    else:
        print(f"[INFO] Analyzed benchmark report: {report_path}")
        print(format_report_summary(cal))


if __name__ == "__main__":
    main()
